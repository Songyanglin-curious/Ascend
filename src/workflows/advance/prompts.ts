function createPromptMessage(
    role: PromptMessage["role"],
    content: string,
): PromptMessage {
    return { role, content };
}

function buildNormalizedQueryPromptMessage(normalizedQuery: string): PromptMessage {
    return createPromptMessage("user", `当前规范化问题：\n${normalizedQuery}`);
}

export function mapHistoryMessagesToPromptMessages(
    messages: BaseMessage[],
): PromptMessage[] {
    return messages.map((message) => {
        switch (message.type) {
            case "human":
                return createPromptMessage("user", message.text);
            case "ai":
                return createPromptMessage("assistant", message.text);
            default:
                throw new Error(`不支持的历史消息类型: ${message.type}`);
        }
    });
}

export function buildNormalizePromptMessages(rawInput: string): PromptMessage[] {
    return [
        createPromptMessage("system", NORMALIZE_SYSTEM_PROMPT),
        createPromptMessage("user", rawInput),
    ];
}

export function buildEvaluatePromptMessages(
    normalizedQuery: string,
    analysisMessages: BaseMessage[],
): PromptMessage[] {
    return [
        createPromptMessage("system", EVALUATE_SYSTEM_PROMPT),
        ...mapHistoryMessagesToPromptMessages(analysisMessages),
        buildNormalizedQueryPromptMessage(normalizedQuery),
    ];
}

export function buildActionPromptMessages(
    systemPrompt: string,
    normalizedQuery: string,
    analysisMessages: BaseMessage[],
): PromptMessage[] {
    return [
        createPromptMessage("system", systemPrompt),
        ...mapHistoryMessagesToPromptMessages(analysisMessages),
        buildNormalizedQueryPromptMessage(normalizedQuery),
    ];
}

export function buildRecognizeIntentPromptMessages(
    lastAssistantOutput: string,
    rawInput: string,
): PromptMessage[] {
    return [
        createPromptMessage("system", RECOGNIZE_INTENT_SYSTEM_PROMPT),
        createPromptMessage("assistant", lastAssistantOutput),
        createPromptMessage("user", rawInput),
    ];
}
